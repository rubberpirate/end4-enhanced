import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const motion = vm.createContext({ Math });
vm.runInContext(readFileSync(new URL('../../modules/ii/notificationPopup/DripMotion.js', import.meta.url), 'utf8').replace('.pragma library', ''), motion);
const m = motion.enter(320, 60, 44, null, 32, 32, 0, false);
assert.equal(motion.sample(m.width, 0), 12);
assert.equal(motion.opacity(m, 0.1, false), 0, 'text waits for capsule expansion');
assert.ok(Math.abs(motion.sample(m.width, 3) - 320) < 0.001);
assert.ok(Math.abs(motion.sample(m.center, 3) - 74) < 0.001);
assert.equal(motion.opacity(m, 3, true), 1);
const beforeMove = motion.sample(m.center, 0.3);
motion.move(m, 114, 0.3, false);
assert.equal(motion.sample(m.center, 0.3), beforeMove, 'interruptions preserve position');
const beforeExit = motion.sample(m.width, 0.35);
motion.leave(m, null, 0, 32, 0.35, false);
assert.equal(motion.sample(m.width, 0.35), beforeExit);
assert.ok(motion.sample(m.center, m.end) + 13 < 32, 'return drop is swallowed by notch');
const early = motion.enter(320, 60, 44, null, 32, 32, 0, false);
motion.leave(early, null, 0, 32, 0.01, false);
assert.equal(motion.opacity(early, 0.01, false), 0, 'early dismissal never flashes content');
const reduced = motion.enter(320, 60, 44, null, 32, 32, 0, true);
assert.equal(motion.sample(reduced.width, 0), 320);
assert.equal(motion.sample(reduced.center, 0), 74);
motion.leave(reduced, null, 0, 32, 1, true);
assert.equal(reduced.end, 1.15);
console.log('MOTION CHECK PASSED');
